def default_prescription(name, category):
    if name in DEFAULT_EXERCISE_PRESCRIPTIONS:
        return DEFAULT_EXERCISE_PRESCRIPTIONS[name]
    if category == "conditioning":
        return "4 rounds controlled"
    if category == "recovery":
        return "10 min easy recovery"
    return "3 x 12 controlled"


def ex(name, prescription, category, rest="", intensity="", notes=""):
    return {
        "name": name,
        "prescription": prescription or default_prescription(name, category),
        "rest": rest,
        "intensity": intensity,
        "notes": notes,
        "category": category,
    }


def workout(
    workout_order,
    title,
    priority,
    priority_order,
    day_type,
    intensity,
    duration,
    goal,
    fatigue_score,
    coach_note,
    exercises,
):
    return {
        "workout_order": workout_order,
        "title": title,
        "priority": priority,
        "priority_order": priority_order,
        "day_type": day_type,
        "intensity": intensity,
        "duration": duration,
        "goal": goal,
        "fatigue_score": fatigue_score,
        "coach_note": coach_note,
        "exercises": [
            {"id": f"ex-{workout_order}-{index}", "order": index, **item}
            for index, item in enumerate(exercises, start=1)
        ],
    }


