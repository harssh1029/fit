def plan_ex(name, prescription="", category="strength"):
    return ex(name, prescription, category)


def premium_workout_title(value):
    acronyms = {"VO2", "RDL", "HM"}
    formatted = []
    for token in value.split(" "):
        if token in {"+", "&"}:
            formatted.append(token)
            continue
        upper = token.upper()
        if upper in acronyms:
            formatted.append(upper)
            continue
        formatted.append(token[:1].upper() + token[1:].lower())
    return " ".join(formatted)


def infer_plan_exercise_category(name, day_type, priority):
    normalized = name.lower()
    if any(
        token in normalized
        for token in [
            "mobility",
            "stretch",
            "recovery",
            "breath",
            "foam",
            "easy walk",
        ]
    ):
        return "recovery"
    if "run" in normalized or normalized.endswith("m") or "threshold" in normalized:
        return "run"
    if any(
        token in normalized
        for token in [
            "assault bike",
            "bike",
            "row",
            "ski",
            "sled",
            "burpee",
            "battle rope",
            "wall balls",
            "carry",
            "erg",
            "box jump",
            "thruster",
            "swing",
            "snatch",
        ]
    ):
        return "conditioning"
    if day_type == "recovery":
        return "recovery"
    if day_type in {"cardio", "hybrid"} and priority != "P1":
        return "conditioning"
    return "strength"


def plan_workout(
    workout_order,
    title,
    priority,
    priority_order,
    day_type,
    intensity,
    duration,
    goal,
    fatigue_score,
    coach_note,
    exercises,
):
    return workout(
        workout_order,
        premium_workout_title(title),
        priority,
        priority_order,
        day_type,
        intensity,
        duration,
        goal,
        fatigue_score,
        coach_note,
        [
            plan_ex(
                item[0],
                item[1] if len(item) > 1 else "",
                item[2] if len(item) > 2 else infer_plan_exercise_category(
                    item[0],
                    day_type,
                    priority,
                ),
            )
            for item in exercises
        ],
    )


def make_plan_weeks(plan_slug, week_specs):
    weeks = []
    for week_number, title, focus, coach_note, recovery_priority, workouts in week_specs:
        weeks.append(
            {
                "id": f"{plan_slug}-w{week_number}",
                "number": week_number,
                "title": title,
                "focus": focus,
                "coach_note": coach_note,
                "recovery_priority": recovery_priority,
                "workouts": [
                    plan_workout(*workout_spec)
                    for workout_spec in workouts
                ],
            }
        )
    return weeks


